#!/usr/bin/env python3
"""
Render assets/logo.svg into every raster the app needs. Run it after the logo changes:

    pip install cairosvg
    python packaging/make_brand_assets.py          # write the files
    python packaging/make_brand_assets.py --check  # exit 1 if the files are stale

Writes assets/logo.png (40 px), assets/logo@2x.png (80 px), assets/icon.png (256 px),
assets/icon.ico (16 to 256 px), contexta_app/embedded_icon_data.py and assets/brand_assets.py.
The embedded copies are the fallback when the files are not shipped (a pip install, for example).
"""

from __future__ import annotations

import base64
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SVG = ROOT / "assets" / "logo.svg"
ICO_SIZES = (16, 24, 32, 48, 64, 128, 256)


def render(size: int) -> bytes:
    import cairosvg

    return cairosvg.svg2png(url=str(SVG), output_width=size, output_height=size)


def build_ico(pngs: dict[int, bytes]) -> bytes:
    header = struct.pack("<HHH", 0, 1, len(pngs))
    offset = 6 + 16 * len(pngs)
    entries, blobs = b"", b""
    for size, blob in sorted(pngs.items()):
        entries += struct.pack("<BBBBHHII", size % 256, size % 256, 0, 0, 1, 32, len(blob), offset + len(blobs))
        blobs += blob
    return header + entries + blobs


def wrap(blob: bytes) -> str:
    text = base64.b64encode(blob).decode("ascii")
    return "(\n" + "\n".join(f'    "{text[i:i + 100]}"' for i in range(0, len(text), 100)) + "\n)\n"


def outputs() -> dict[Path, bytes]:
    logo, logo2x, icon = render(40), render(80), render(256)
    ico = build_ico({size: render(size) for size in ICO_SIZES})
    embedded = (
        '"""Embedded copies of the brand images, used when the files in assets/ are not shipped.\n\n'
        'Generated by packaging/make_brand_assets.py from assets/logo.svg. Do not edit by hand."""\n\n'
        f"EMBEDDED_ICON_PNG_BASE64 = {wrap(icon)}\n"
        f"EMBEDDED_LOGO_PNG_BASE64 = {wrap(logo)}\n"
        f"EMBEDDED_LOGO_2X_PNG_BASE64 = {wrap(logo2x)}"
    )
    legacy = f'"""Embedded brand assets for Contexta. Generated by packaging/make_brand_assets.py."""\n\nICON_PNG_B64 = {wrap(icon)}'
    return {
        ROOT / "assets" / "logo.png": logo,
        ROOT / "assets" / "logo@2x.png": logo2x,
        ROOT / "assets" / "icon.png": icon,
        ROOT / "assets" / "icon.ico": ico,
        ROOT / "contexta_app" / "embedded_icon_data.py": embedded.encode("utf-8"),
        ROOT / "assets" / "brand_assets.py": legacy.encode("utf-8"),
    }


def main() -> int:
    stale = []
    for path, data in outputs().items():
        if "--check" in sys.argv:
            if not path.exists() or path.read_bytes() != data:
                stale.append(path.name)
        else:
            path.write_bytes(data)
            print(f"wrote {path.relative_to(ROOT)} ({len(data):,} bytes)")
    if stale:
        print("stale: " + ", ".join(stale) + ". Run python packaging/make_brand_assets.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
