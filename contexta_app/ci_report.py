"""
ci_report.py - the engine behind the Contexta GitHub Action.

Builds the context for a pull request: the diff against the base branch, the files it
reaches, the tests worth running, and a redacted pack of the changed code that fits a
token budget. Optionally posts a short summary as a PR comment, updated in place.

    python -m contexta_app.ci_report --base origin/main --budget 24000 --output contexta-pr-context.md

The comment holds file paths and numbers only, never source. The pack file holds source
and goes through the same secret redaction as every other pack.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import urllib.error
import urllib.request
from pathlib import Path

MARKER = "<!-- contexta-pr-context -->"
MAX_COMMENT_CHARS = 60000
MAX_LISTED = 25


def _log(message: str) -> None:
    sys.stderr.write(message + "\n")


def collect_impact(project: Path, base: str, depth: int = 3) -> dict:
    """Changed files (merge-base diff against ``base``) and what they reach, from the project graph."""
    from contexta_app.graph import ProjectGraph
    from contexta_app.scanner import get_git_changed_files

    changed = get_git_changed_files(project, base_ref=base) or []
    rel = sorted({p.relative_to(project).as_posix() for p in changed})
    graph = ProjectGraph(project)
    try:
        graph.update()
        impact = graph.impact(rel, depth=depth, limit=60) if rel else {"changed": [], "impacted": [], "impacted_total": 0, "tests": [], "tests_total": 0, "cochanged": []}
    finally:
        graph.close()
    impact["changed_all"] = rel
    return impact


def _bullets(items: list[str], limit: int = MAX_LISTED) -> list[str]:
    lines = [f"- `{item}`" for item in items[:limit]]
    if len(items) > limit:
        lines.append(f"- ... and {len(items) - limit} more")
    return lines or ["- none"]


def render_summary(impact: dict, base: str, tokens: int | None = None, budget: int | None = None, artifact: str = "") -> str:
    changed = impact["changed_all"]
    tests = [t["path"] for t in impact["tests"]]
    impacted = impact["impacted"]
    lines = [
        MARKER,
        "### Contexta: context for this PR",
        "",
        f"**{len(changed)}** changed file(s) against `{base}`, reaching **{impact['impacted_total']}** more file(s). "
        f"**{impact['tests_total']}** test file(s) look relevant.",
    ]
    if tokens is not None:
        fit = f"~{tokens / 1000:.1f}k tokens" + (f" (budget {budget / 1000:.0f}k)" if budget else "")
        lines.append(f"Context pack: {fit}, secrets redacted." + (f" Download the `{artifact}` artifact from this run." if artifact else ""))
    lines += ["", "<details><summary>Changed files</summary>", ""] + _bullets(changed) + ["", "</details>"]
    lines += ["", "<details open><summary>Tests to run</summary>", ""] + _bullets(tests) + ["", "</details>"]
    if impacted:
        lines += ["", "<details><summary>Files these changes reach</summary>", ""]
        lines += [f"- `{r['path']}` (distance {r['distance']})" for r in impacted[:MAX_LISTED]]
        if len(impacted) > MAX_LISTED:
            lines.append(f"- ... and {impact['impacted_total'] - MAX_LISTED} more")
        lines += ["", "</details>"]
    lines += ["", "<sub>Generated by [Contexta](https://github.com/pablokaua03/contexta). Paths only, no source in this comment.</sub>"]
    return "\n".join(lines)[:MAX_COMMENT_CHARS]


def build_pack(project: Path, base: str, budget: int) -> tuple[str, dict]:
    """The redacted PR pack, through the same planner as ``contexta --for review``."""
    from contexta_app.cli import _render_with_budget, build_parser, build_plan

    args = build_parser().parse_args([str(project), "--for", "review", "--base", base, "--budget", str(budget), "--stdout"])
    plan = build_plan(args, project, stdout_isatty=False)
    return _render_with_budget(plan, lambda text, tag="": _log(text))


def header(impact: dict, base: str) -> str:
    tests = [t["path"] for t in impact["tests"]]
    lines = [
        f"# Pull request context (against `{base}`)",
        "",
        f"Changed files ({len(impact['changed_all'])}):",
        *_bullets(impact["changed_all"], 40),
        "",
        f"Tests worth running ({impact['tests_total']}):",
        *_bullets(tests, 40),
        "",
        "---",
        "",
    ]
    return "\n".join(lines)


def find_pr_number(event_path: str | None = None) -> int | None:
    path = event_path or os.environ.get("GITHUB_EVENT_PATH")
    if not path or not Path(path).is_file():
        return None
    try:
        event = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    number = (event.get("pull_request") or {}).get("number") or event.get("number")
    return int(number) if number else None


def _request(method: str, url: str, token: str, payload: dict | None = None):
    data = json.dumps(payload).encode("utf-8") if payload is not None else None
    req = urllib.request.Request(
        url, data=data, method=method,
        headers={"Authorization": f"Bearer {token}", "Accept": "application/vnd.github+json", "X-GitHub-Api-Version": "2022-11-28", "Content-Type": "application/json"},
    )
    with urllib.request.urlopen(req, timeout=30) as resp:  # noqa: S310 - the API host comes from GITHUB_API_URL
        body = resp.read().decode("utf-8")
    return json.loads(body) if body else None


def post_comment(body: str, repo: str, pr: int, token: str, api_url: str = "https://api.github.com", request=_request) -> str:
    """Create the Contexta comment on the PR, or update the one a previous run left. Returns 'created' or 'updated'."""
    base = f"{api_url.rstrip('/')}/repos/{repo}/issues"
    for page in range(1, 51):  # 5000 comments is far past any real PR
        comments = request("GET", f"{base}/{pr}/comments?per_page=100&page={page}", token) or []
        for comment in comments:
            if MARKER in (comment.get("body") or ""):
                request("PATCH", f"{base}/comments/{comment['id']}", token, {"body": body})
                return "updated"
        if len(comments) < 100:
            break
    request("POST", f"{base}/{pr}/comments", token, {"body": body})
    return "created"


def write_output(name: str, value: str) -> None:
    target = os.environ.get("GITHUB_OUTPUT")
    if target:
        with open(target, "a", encoding="utf-8") as handle:
            handle.write(f"{name}={value}\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m contexta_app.ci_report", description="Build the Contexta context for a pull request.")
    parser.add_argument("--project", default=".", help="Project folder (default: .)")
    parser.add_argument("--base", required=True, help="Base ref to compare against, for example origin/main")
    parser.add_argument("--budget", type=int, default=24000, help="Token budget for the whole file (default: 24000)")
    parser.add_argument("--output", default="contexta-pr-context.md", help="Where to write the pack")
    parser.add_argument("--comment", action="store_true", help="Post or update a summary comment on the PR")
    parser.add_argument("--summary-file", default="", help="Also write the summary Markdown here")
    parser.add_argument("--depth", type=int, default=3)
    args = parser.parse_args(argv)

    from contexta_app.renderer import estimate_tokens
    from contexta_app.scanner import GitError, git_ref_exists

    if args.budget <= 0:
        _log("--budget must be a positive integer.")
        return 2
    project = Path(args.project).resolve()
    try:
        if not git_ref_exists(project, args.base):
            _log(
                f"The base ref '{args.base}' is not available in this checkout.\n"
                "Use actions/checkout with `fetch-depth: 0` (or fetch the base branch) before this action."
            )
            return 2
        impact = collect_impact(project, args.base, args.depth)
        head = header(impact, args.base)
        pack_budget = max(1000, args.budget - estimate_tokens(head))
        pack, stats = build_pack(project, args.base, pack_budget)
    except (GitError, ValueError) as exc:
        _log(f"Error: {exc}")
        return 2

    text = head + pack
    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    tokens = estimate_tokens(text)
    summary = render_summary(impact, args.base, tokens, args.budget, artifact="contexta-pr-context")
    if args.summary_file:
        Path(args.summary_file).write_text(summary, encoding="utf-8")
    step_summary = os.environ.get("GITHUB_STEP_SUMMARY")
    if step_summary:
        with open(step_summary, "a", encoding="utf-8") as handle:
            handle.write(summary + "\n")
    write_output("pack-path", str(out))
    write_output("tokens", str(tokens))
    write_output("changed-files", str(len(impact["changed_all"])))
    write_output("tests", str(impact["tests_total"]))
    _log(f"Wrote {out} (~{tokens / 1000:.1f}k tokens, {len(impact['changed_all'])} changed file(s), {impact['tests_total']} test file(s) to run).")

    if args.comment:
        token, repo, pr = os.environ.get("GITHUB_TOKEN", ""), os.environ.get("GITHUB_REPOSITORY", ""), find_pr_number()
        if not (token and repo and pr):
            _log("Skipping the PR comment: needs GITHUB_TOKEN, GITHUB_REPOSITORY and a pull_request event.")
        else:
            try:
                result = post_comment(summary, repo, pr, token, os.environ.get("GITHUB_API_URL", "https://api.github.com"))
                _log(f"PR comment {result}.")
            except (urllib.error.URLError, OSError) as exc:
                _log(f"Could not post the PR comment ({exc}). Pull requests from forks get a read-only token; the artifact is still uploaded.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
